import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile, copyFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import net from 'node:net';

const root = process.cwd();
const out = join(root, 'out');
const privateDir = join(out, 'private');
const publicDir = join(out, 'public');
const originalDir = join(privateDir, 'original');
const workDir = join(privateDir, 'work');
const firmwareName = 'nexahome-lab-s1-v1.0.bin';
const labToken = 'LAB-ONLY-KEY-7C2A'; // Fictitious and never accepted by a real service.
const manifest = {
  device: 'NexaHome Lab S1',
  kind: 'software-simulated educational device',
  version: '1.0',
  mcu: 'virtual 32-bit MCU',
  flash_bytes: 524288,
  sensor: 'virtual temperature sensor',
  debug_interface: 'UART simulated as a boot log',
  transport: 'TCP loopback, newline-delimited JSON',
  service: 'local lab collector',
  token: labToken
};
function sha256(bytes) { return createHash('sha256').update(bytes).digest('hex'); }
function assert(value, message) { if (!value) throw new Error(message); }
async function main() {
  await Promise.all([originalDir, workDir, publicDir].map(p => mkdir(p, { recursive: true })));
  const manifestBytes = Buffer.from(JSON.stringify(manifest), 'utf8');
  const header = Buffer.alloc(8);
  header.write('NHFW', 0, 'ascii');
  header.writeUInt32LE(manifestBytes.length, 4);
  const image = Buffer.concat([header, manifestBytes]);
  const originalPath = join(originalDir, firmwareName);
  const workPath = join(workDir, firmwareName);
  await writeFile(originalPath, image);
  await copyFile(originalPath, workPath);
  const original = await readFile(originalPath);
  const working = await readFile(workPath);
  assert(sha256(original) === sha256(working), 'Preservation hash mismatch');
  const size = (await stat(originalPath)).size;
  const hashes = [
    'name=' + firmwareName,
    'origin=generated from src/lab-assessment.mjs in this repository',
    'size_bytes=' + size,
    'sha256_original=' + sha256(original),
    'sha256_working=' + sha256(working),
    'analysis_date=' + new Date().toISOString(),
    'original_location=out/private/original/ (excluded from Git)',
    'working_location=out/private/work/ (excluded from Git)'
  ].join('\n') + '\n';
  await writeFile(join(publicDir, 'hashes.txt'), hashes);
  assert(working.subarray(0, 4).toString('ascii') === 'NHFW', 'Unknown firmware format');
  const declaredLength = working.readUInt32LE(4);
  assert(declaredLength === working.length - 8, 'Invalid manifest length');
  const parsed = JSON.parse(working.subarray(8).toString('utf8'));
  assert(parsed.token === labToken, 'Expected lab token not found');
  const uart = 'BOOT NexaHome Lab S1 v1.0\nDEBUG enrollment token=' + parsed.token + '\nREADY\n';
  await writeFile(join(publicDir, 'uart-observation.txt'), '# Simulated UART boot log, generated by lab device\n' + uart);

  let received = '';
  const server = net.createServer(socket => {
    socket.on('data', chunk => { received += chunk.toString('utf8'); });
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const address = server.address();
  const payload = JSON.stringify({
    device_id: 'LAB-S1-001',
    temperature_c: 23.4,
    token: parsed.token,
    command: 'telemetry'
  }) + '\n';
  await new Promise((resolve, reject) => {
    const client = net.connect(address.port, '127.0.0.1');
    client.once('error', reject);
    client.once('connect', () => client.end(payload, 'utf8'));
    client.once('close', resolve);
  });
  await new Promise((resolve, reject) => server.close(err => err ? reject(err) : resolve()));
  assert(received === payload, 'Network payload differs from transmitted bytes');
  assert(received.includes(labToken), 'Expected lab token not observed on listener');
  await writeFile(join(publicDir, 'network-observation.txt'),
    '# Bytes received by local TCP collector (application-layer transcript; not a packet capture)\n' +
    'source=127.0.0.1:ephemeral\ndestination=127.0.0.1:ephemeral\n' +
    'transport=TCP; TLS=not used; application framing=newline-delimited JSON\n' +
    'payload_utf8=' + received);
  const analysis = [
    '# Firmware analysis generated from preserved working copy',
    'format=NHFW custom educational container',
    'header_offset=0; magic=NHFW',
    'manifest_length_offset=4; manifest_offset=8; manifest_bytes=' + declaredLength,
    'filesystem=none; partitions=none; executable code=none',
    'manifest_device=' + parsed.device,
    'manifest_transport=' + parsed.transport,
    'manifest_debug_interface=' + parsed.debug_interface,
    'synthetic_token_at_json_field=token; value=' + parsed.token,
    'assessment=token is directly readable in image; this is a deliberate lab weakness',
    ''
  ].join('\n');
  await writeFile(join(publicDir, 'firmware-analysis.txt'), analysis);
  const checks = {
    firmware_hash_match: sha256(original) === sha256(working),
    image_structure_valid: declaredLength === working.length - 8,
    token_in_firmware: working.includes(Buffer.from(labToken)),
    token_in_uart: uart.includes(labToken),
    plaintext_network_payload: received.includes(labToken),
    loopback_only: address.address === '127.0.0.1'
  };
  assert(Object.values(checks).every(Boolean), 'A lab check failed');
  await writeFile(join(publicDir, 'checks.json'), JSON.stringify(checks, null, 2) + '\n');
  console.log(JSON.stringify({ status: 'PASS', firmware_sha256: sha256(original), size_bytes: size, checks }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
